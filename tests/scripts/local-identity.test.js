/** @vitest-environment node */
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { sourceIdentity, sourceRoots } from '../../scripts/local/identity.mjs';

const roots = [];
function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'linejam-source-identity-'));
  roots.push(root);
  for (const relative of sourceRoots) {
    const output = join(root, relative);
    if (statSync(relative).isDirectory()) {
      mkdirSync(output, { recursive: true });
      writeFileSync(join(output, 'source.txt'), 'fixture source');
    } else {
      mkdirSync(dirname(output), { recursive: true });
      writeFileSync(
        output,
        relative === 'package.json' ? readFileSync(relative) : 'fixture source'
      );
    }
  }
  return root;
}

afterEach(() => {
  for (const root of roots.splice(0))
    rmSync(root, { recursive: true, force: true });
});

it('keeps source identity stable across generated WASM while tracking Rust source changes', async () => {
  const root = fixture();
  const before = await sourceIdentity(root);
  mkdirSync(join(root, 'public/entry-wasm'));
  writeFileSync(
    join(root, 'public/entry-wasm/entry_bg.wasm'),
    'generated bytes'
  );
  writeFileSync(join(root, 'public/entry-wasm/entry.js'), 'generated glue');
  expect(await sourceIdentity(root)).toEqual(before);
  writeFileSync(join(root, 'crates/source.txt'), 'changed Rust source');
  const changed = await sourceIdentity(root);
  expect(changed.frontend.sha256).not.toBe(before.frontend.sha256);
  expect(changed.backend.sha256).toBe(before.backend.sha256);
});

it('still rejects symlinks in source inputs', async () => {
  const root = fixture();
  symlinkSync(join(root, 'package.json'), join(root, 'crates/linked.rs'));
  await expect(sourceIdentity(root)).rejects.toThrow(
    'Source identity refuses a symlink'
  );
});
