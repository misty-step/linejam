#!/usr/bin/env node
// Mechanically derive app inputs from the locked Active Folio assets
// (DESIGN.md [D1-2]). Never edit the outputs by hand: they are byte copies of
// folio/assets/** or raster renders of folio/assets/mark.svg.
//
//   node scripts/design/folio-assets.mjs          write outputs
//   node scripts/design/folio-assets.mjs --check  fail on any drift
//   node scripts/design/folio-assets.mjs --icons  also re-render raster icons
//                                                 (needs rsvg-convert + ImageMagick)
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const assets = join(root, 'folio/assets');
const publicFolio = join(root, 'public/folio');
const generatedModule = join(root, 'lib/design/folio.generated.ts');

/** Emblem order is load-bearing: stored avatar ids map onto it by index. */
export const EMBLEMS = [
  'loom',
  'vesper',
  'prism',
  'clover',
  'orrery',
  'arch',
  'pinwheel',
  'lattice',
];

export function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/** Verify every locked file against the manifest; throw on any mismatch. */
export function verifyLockedAssets(directory = assets) {
  const manifest = JSON.parse(
    readFileSync(join(directory, 'checksums.json'), 'utf8')
  );
  const mismatches = [];
  for (const [file, expected] of Object.entries(manifest)) {
    const actual = sha256(readFileSync(join(directory, file)));
    if (actual !== expected)
      mismatches.push(`${file}: ${actual} != ${expected}`);
  }
  if (mismatches.length) {
    throw new Error(`Locked folio assets drifted:\n${mismatches.join('\n')}`);
  }
  return manifest;
}

export function renderGeneratedModule(directory = assets) {
  const svg = (name) => readFileSync(join(directory, name), 'utf8');
  const emblems = EMBLEMS.map(
    (id) => `  ${id}: ${JSON.stringify(svg(`emblem-${id}.svg`))},`
  ).join('\n');
  return `// Generated by scripts/design/folio-assets.mjs from folio/assets/**.
// Do not edit: these strings are the locked files, byte for byte.

export const FOLIO_MARK_SVG = ${JSON.stringify(svg('mark.svg'))};

export const FOLIO_EMBLEM_SVG = {
${emblems}
} as const;
`;
}

function outputs(manifest) {
  const files = Object.keys(manifest).concat('checksums.json');
  return [
    [generatedModule, Buffer.from(renderGeneratedModule())],
    ...files.map((file) => [
      join(publicFolio, file),
      readFileSync(join(assets, file)),
    ]),
  ];
}

function renderIcons() {
  const tokens = JSON.parse(readFileSync(join(assets, 'tokens.json'), 'utf8'));
  const ink = tokens.light.accent;
  const paper = tokens.light.bg;
  const mark = readFileSync(join(assets, 'mark.svg'), 'utf8');
  const work = mkdtempSync(join(tmpdir(), 'linejam-icons-'));
  try {
    // Color only through currentColor: the root element's color property.
    const tinted = join(work, 'mark.svg');
    writeFileSync(tinted, mark.replace('<svg ', `<svg color="${ink}" `));
    const render = (size, markSize, out) => {
      const glyph = join(work, `glyph-${size}-${markSize}.png`);
      execFileSync('rsvg-convert', [
        '-w',
        String(markSize),
        '-h',
        String(markSize),
        '-o',
        glyph,
        tinted,
      ]);
      execFileSync('convert', [
        '-size',
        `${size}x${size}`,
        `xc:${paper}`,
        glyph,
        '-gravity',
        'center',
        '-composite',
        '-alpha',
        'off',
        '-strip',
        '-depth',
        '8',
        out,
      ]);
    };
    const pub = (name) => join(root, 'public', name);
    // Regular icons: the 20-unit mark fills the 18-unit diamond, so 80% of the
    // canvas keeps comfortable margins. Maskable: 64% stays well inside the
    // central 80% safe zone.
    render(180, 144, pub('apple-touch-icon.png'));
    render(192, 154, pub('icon-192.png'));
    render(512, 410, pub('icon-512.png'));
    render(512, 328, pub('icon-maskable-512.png'));
    render(16, 16, join(work, 'f16.png'));
    render(32, 28, join(work, 'f32.png'));
    execFileSync('convert', [
      join(work, 'f16.png'),
      join(work, 'f32.png'),
      pub('favicon.ico'),
    ]);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function main() {
  const check = process.argv.includes('--check');
  const manifest = verifyLockedAssets();
  const drift = [];
  for (const [path, bytes] of outputs(manifest)) {
    if (check) {
      if (!existsSync(path) || !readFileSync(path).equals(bytes)) {
        drift.push(path.slice(root.length + 1));
      }
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    if (path.startsWith(publicFolio)) {
      copyFileSync(join(assets, path.slice(publicFolio.length + 1)), path);
    } else {
      writeFileSync(path, bytes);
    }
  }
  if (drift.length) {
    throw new Error(
      `Folio-derived files are stale; run node scripts/design/folio-assets.mjs:\n${drift.join('\n')}`
    );
  }
  if (!check && process.argv.includes('--icons')) renderIcons();
  console.log(
    check
      ? 'Folio assets verified: checksums match and derived files are current.'
      : 'Folio-derived files written.'
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
