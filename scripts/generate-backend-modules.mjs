#!/usr/bin/env node
/**
 * Writes cloudflare/modules.generated.ts: every Convex function module as a
 * lazy import, keyed by its Convex module path. `--check` fails when the
 * committed file is stale.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import * as prettier from 'prettier';

const root = path.resolve(import.meta.dirname, '..');
const convexDir = path.join(root, 'convex');
const target = path.join(root, 'cloudflare', 'modules.generated.ts');
// Loaded explicitly by cloudflare/backend.ts, or not function modules.
const EXCLUDED = new Set(['schema', 'crons', 'http', 'auth.config']);

async function modulePaths(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== '_generated')
        found.push(...(await modulePaths(absolute)));
    } else if (
      entry.name.endsWith('.ts') &&
      !/\.(d|test|spec)\.ts$/.test(entry.name)
    ) {
      const name = path
        .relative(convexDir, absolute)
        .replace(/\.ts$/, '')
        .split(path.sep)
        .join('/');
      if (!EXCLUDED.has(name)) found.push(name);
    }
  }
  return found.sort();
}

const names = await modulePaths(convexDir);
const unformatted = `// Generated by scripts/generate-backend-modules.mjs. Do not edit.
import type { ModuleSource } from '@parlor/cloudflare';

export const modules = {
${names.map((name) => `  '${name}': () => import('../convex/${name}'),`).join('\n')}
} satisfies Record<string, ModuleSource>;
`;
const source = await prettier.format(unformatted, {
  ...(await prettier.resolveConfig(target)),
  filepath: target,
});

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) {
    console.error(
      'cloudflare/modules.generated.ts is stale; run node scripts/generate-backend-modules.mjs'
    );
    process.exit(1);
  }
} else {
  await writeFile(target, source);
}
